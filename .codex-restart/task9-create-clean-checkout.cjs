const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const source = path.resolve(__dirname, '..');
const git = (cwd, ...args) => cp.execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
if (git(source, 'branch', '--show-current') !== '2026-09-08-settings-refactor') throw new Error('Settings branch required');
const head = git(source, 'rev-parse', 'HEAD');
if (head.startsWith('c0821b6')) throw new Error('Commit the remaining reviewed Settings changes first');
const dirty = git(source, 'diff', '--name-only').split('\n').filter(Boolean);
if (dirty.some(name => name !== 'music_app/static/css/gallery-main.css')) throw new Error('Uncommitted Settings changes remain');
if (git(source, 'diff', '--cached', '--name-only')) throw new Error('Index must be empty');
const target = path.join(path.dirname(source), `settings-final-${head.slice(0, 10)}`);
if (fs.existsSync(target)) throw new Error('Final checkout already exists; inspect rather than overwrite');
git(source, 'clone', '--no-hardlinks', '--single-branch', '--branch', '2026-09-08-settings-refactor', source, target);
if (git(target, 'rev-parse', 'HEAD') !== head) throw new Error('Cloned commit mismatch');
fs.symlinkSync(path.join(source, 'node_modules'), path.join(target, 'node_modules'), 'junction');
fs.appendFileSync(path.join(target, '.git', 'info', 'exclude'), '\n.codex-restart/\n');
fs.mkdirSync(path.join(target, '.codex-restart'));
if (git(target, 'status', '--porcelain')) throw new Error('Final checkout is not clean');
const result = { source, target, head, branch: '2026-09-08-settings-refactor', created: new Date().toISOString() };
fs.writeFileSync(path.join(__dirname, 'task9-clean-checkout.json'), JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify(result));
