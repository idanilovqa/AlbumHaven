const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const Module = require('node:module');
const repo = path.resolve(__dirname, '..');
const testPath = path.join(repo, 'tests/js/runtime/utility-list-builders.test.js');
const source = fs.readFileSync(testPath, 'utf8');
const harness = new Module(testPath, module);
harness.filename = testPath;
harness.paths = Module._nodeModulePaths(path.dirname(testPath));
harness._compile(source.slice(0, source.indexOf("test('Appearance navigation")) + '\nmodule.exports = loadHelpers;', testPath);
const context = harness.exports();
const responseTestPath = path.join(repo, 'tests/js/runtime/response-state-helpers.test.js');
const responseTest = fs.readFileSync(responseTestPath, 'utf8');
const responseHarness = new Module(responseTestPath, module);
responseHarness.filename = responseTestPath;
responseHarness.paths = Module._nodeModulePaths(path.dirname(responseTestPath));
responseHarness._compile(responseTest.slice(0, responseTest.indexOf('function cacheAutomaticSearchSelection'))
  + responseTest.match(/function loadHelpers\(\) \{[\s\S]*?\n\}/)[0]
  + '\nmodule.exports = loadHelpers;', responseTestPath);
const responseContext = responseHarness.exports();
context.appBootstrap = responseContext.appBootstrap;
context.state.ui = responseContext.state.ui;
context.state.gallery = responseContext.state.gallery;
vm.runInContext(fs.readFileSync(path.join(repo, 'music_app/static/js/runtime/response-state-helpers.js'), 'utf8'), context);
const fixture = JSON.parse(fs.readFileSync(path.join(__dirname, 'task9-identity-optimistic-sanitized.json')));
const groups = [{artist: 'ДДТ', albums: fixture.preEditAlbums}];
context.state.view = {...context.state.view, selected_artist: 'ДДТ', related_artists: [], artist_groups: groups, primary_artist_groups: groups, family_artist_groups: []};
context.getAlbumRequestKey = album => album.album_ref || album.key;
context.getAlbumIdentity = album => album.key;
context.deepCloneJson = value => JSON.parse(JSON.stringify(value));
context.formatAlbumDuration = () => '';
context.findVisibleAlbumByTrackPaths = () => fixture.preEditAlbums[1];
vm.runInContext(fs.readFileSync(path.join(repo, 'music_app/static/js/runtime/utility-loaders-and-cover-lookup.js'), 'utf8'), context);
const candidates = context.buildOptimisticUpdatedAlbumsFromEdits(fixture.post.album, fixture.post.updates);
const counts = albums => albums.map(album => ({key: album.key, name: album.name, count: album.tracks?.length, preview: album.track_count_preview}));
console.log(JSON.stringify({phase:'candidates',albums: counts(candidates)}));
context.applyUpdatedAlbumsToCurrentView(candidates, {originalAlbum: fixture.post.album, tagEdits: fixture.post.updates, skipRender:true});
console.log(JSON.stringify({phase:'merged',albums: counts(context.state.view.artist_groups.flatMap(group=>group.albums))}));
