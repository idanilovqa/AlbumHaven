function buildRuntimeBundle() {
  const chunks = [
    '// Generated by scripts/build-runtime-bundle.cjs. Do not edit by hand.',
  ];
  for (const scriptPath of RUNTIME_SCRIPT_PATHS) {
    const absolutePath = path.join(repoRoot, 'music_app', 'static', scriptPath);
    const source = fs.readFileSync(absolutePath, 'utf8').replace(/\s+$/u, '');
    chunks.push(`// BEGIN ${scriptPath}`);
    chunks.push(source);
    chunks.push(`// END ${scriptPath}`);
  }
  return `${chunks.join('\n\n')}\n`;
}

function writeRuntimeBundle() {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, buildRuntimeBundle(), 'utf8');
}

if (require.main === module) {
  writeRuntimeBundle();
  console.log(`Wrote ${path.relative(repoRoot, outputPath)} from ${RUNTIME_SCRIPT_PATHS.length} runtime modules.`);
}

