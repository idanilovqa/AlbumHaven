@pytest.mark.asyncio
@pytest.mark.parametrize('family,kind', [('review', 'start'), ('review', 'status'), ('review', 'cancel'),
    ('job', 'start'), ('job', 'resume'), ('job', 'status'), ('job', 'cancel')])
@pytest.mark.parametrize('failure', ['missing', 'duplicate', 'foreign_account', 'old_session'])
async def test_every_new_ui_action_requires_exact_current_account_session_context(monkeypatch, family, kind, failure):
    with running(monkeypatch) as (db, handle, catalog):
        progress = reviewed(handle, payload_rows(1))
        prior_ticket = handle.owner.next_ticket
        if family == 'review':
            kwargs = dict(payload=payload_rows(1)) if kind == 'start' else {}
            req, auth, reads = review_request(monkeypatch, handle, kind, **kwargs)
        else:
            kwargs = dict(payload=payload_rows(1), inventory=progress.result.inventory_sha256,
                review_sha256=review_sha(progress)) if kind in ('start', 'resume') else {}
            req, auth, reads = job_request(monkeypatch, handle, kind, progress.result.command, **kwargs)
        if failure == 'missing':
            req.scope['headers'][:] = [(key, value) for key, value in req.scope['headers']
                if key != b'x-albumhaven-foobar-context']
        elif failure == 'duplicate':
            req.scope['headers'].append((b'x-albumhaven-foobar-context', b'0' * 64))
        elif failure == 'foreign_account':
            ctx = requested_context(None)
            sign_ui_request(req, ctx=replace(ctx, actor=replace(ctx.actor, account_id=2, session_id=5),
                target_account_id=2))
        else:
            auth.session_id = 4  # old browser marker is still for session 3
        response = await (route._run_review(req, kind) if family == 'review' else route._run_job(req, kind))
        value = decoded(response)
        assert response.status_code == (400 if failure in ('missing', 'duplicate') else 409)
        assert 'result' not in value and reads[0] == 0
        assert handle.owner.next_ticket == prior_ticket and handle.owner.current is None
        assert handle.owner.last_review is progress and not db.job_rows and not db.attempts


