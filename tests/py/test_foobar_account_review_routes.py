@pytest.mark.asyncio
async def test_actual_resume_review_preserves_ready_then_confirmation_fences_old_session(monkeypatch):
    from tests.py.foobar_account_import_jobs_testing import start, prepare
    db = install(monkeypatch)
    original, cmd, batch, upload = start(db, payload=PAYLOAD)
    try:
        prepare(original, batch, upload)
    finally:
        upload.close()
    prior_attempt = db.attempts[(1, SOURCE, JOB, 1, 1)].copy()
    current = replace(original, actor=replace(original.actor, session_id=4))
    with running(monkeypatch, db=db) as (db, handle, catalog):
        before = snapshot(db)
        req, auth, reads = review_request(monkeypatch, handle, 'start', payload=PAYLOAD,
            resume=True, ctx=current)
        response = await route.foobar_account_review_start(req)
        assert response.status_code == 202
        progress = settled_review(handle)
        assert progress.phase == 'review_ready' and progress.result.resume is True
        assert snapshot(db) == before and db.attempts[(1, SOURCE, JOB, 1, 1)] == prior_attempt
        req, auth, reads = review_request(monkeypatch, handle, 'status', ctx=current)
        response = await route.foobar_account_review_status(req)
        wire = decoded(response)['result']['review']
        assert response.status_code == 200 and wire['resume'] is True
        req, auth, reads = job_request(monkeypatch, handle, 'resume', cmd,
            inventory=wire['inventory_sha256'], payload=PAYLOAD, review_sha256=wire['review_sha256'])
        auth.session_id = 4
        sign_ui_request(req, ctx=current)
        response = await route.foobar_account_job_resume(req)
        assert response.status_code == 202
        complete = settled(handle)
        assert complete.phase == 'completed' and complete.status.confirmed_through == 1
        assert db.attempts[(1, SOURCE, JOB, 1, 1)]['state'] == 'discarded'
        assert db.attempts[(1, SOURCE, JOB, 1, 2)]['state'] == 'confirmed'
        assert db.attempts[(1, SOURCE, JOB, 1, 2)]['original_session_id'] == 4
        assert db.keys[prior_attempt['prepare_key']]['state'] == 'tombstone'
        assert len(db.source_rows) == 1 and db.calls.count(f._COMMIT_SQL) == 1
