def command_header(req, mutate):
    # Operate only on synthetic wire bytes before Starlette caches the headers.
    headers = req.scope['headers']
    result = []
    for key, value in headers:
        if key == b'x-albumhaven-foobar-command':
            body = json.loads(value)
            mutate(body)
            value = json.dumps(body, separators=(',', ':')).encode()
        result.append((key, value))
    req.scope['headers'][:] = result


@pytest.mark.asyncio
async def test_actual_review_start_status_then_exact_job_v2_confirmation(monkeypatch):
    payload = payload_rows(103)
    with running(monkeypatch) as (db, handle, catalog):
        before = snapshot(db)
        req, auth, reads = review_request(monkeypatch, handle, 'start', payload=payload)
        response = await route.foobar_account_review_start(req)
        accepted = decoded(response)
        assert response.status_code == 202 and accepted['phase'] == 'accepted_for_review'
        assert accepted['protocol'] == 'foobar_account_review_v4'
        assert accepted['durable_start_confirmed'] is False
        assert accepted['context_scope'] == 'account-foobar-v1'
        assert len(accepted['context_ref']) == 64 and reads[0] == 1
        actual = settled_review(handle, timeout=30.0)
        assert actual.phase == 'review_ready' and snapshot(db) == before
        req, auth, reads = review_request(monkeypatch, handle, 'status')
        response = await route.foobar_account_review_status(req)
        value = decoded(response)
        assert response.status_code == 200 and value['context_ref'] == accepted['context_ref']
        wire = value['result']['review']
        assert wire['review_sha256'] == review_sha(actual)
        assert wire['resume'] is False and wire['checked_rows'] == 103 and wire['start_offset'] == 0
        assert wire['proposed_counts'] == [0, 103, 0, 0, 0, 0, 0]
        assert wire['review_counts'] == [103, 103, 0, 0, 0, 0]
        assert wire['advisory_not_reservation'] is True
        assert set(wire) == {'command', 'inventory_sha256', 'resume', 'review_sha256',
            'checked_rows', 'start_offset', 'planned_batches', 'proposed_counts',
            'review_counts', 'problems', 'problems_truncated', 'advisory_not_reservation',
            'conflicts', 'conflict_count', 'conflict_after', 'conflict_next', 'conflict_remaining', 'problem_items', 'problem_count', 'problem_after', 'problem_next', 'problem_remaining'}
        assert wire['conflicts'] == [] and wire['conflict_count'] == 0
        assert wire['conflict_after'] == 0 and wire['conflict_next'] is None
        assert wire['conflict_remaining'] == 0
        assert len(wire['problems']) == 32 and wire['problems_truncated']
        assert 'Track' not in json.dumps(wire['problems'])
        assert len(wire['problem_items']) == 32 and wire['problem_count'] == 103
        assert wire['problem_after'] == 0 and wire['problem_remaining'] == 71
        encoded = json.dumps(wire)
        for private in ('window_seals', 'proposal_sha256', 'prepared', 'observation_ref',
                        'track_id', 'decision_ref', '/unknown-'):
            assert private not in encoded
        cmd = jobs.FoobarJobCommand(**wire['command'])
        req, auth, reads = job_request(monkeypatch, handle, 'start', cmd,
            inventory=wire['inventory_sha256'], payload=payload, review_sha256=wire['review_sha256'])
        response = await route.foobar_account_job_start(req)
        accepted_job = decoded(response)
        assert response.status_code == 202 and accepted_job['protocol'] == 'foobar_account_job_v3'
        assert accepted_job['durable_start_confirmed'] is False
        assert accepted_job['context_ref'] == accepted['context_ref']
        completed = settled(handle, timeout=30.0)
        assert completed.phase == 'completed' and completed.status.confirmed_through == 103
        assert_confirmed_terminals(db, completed, 103)
        assert len(db.attempts) == actual.result.proposed.planned_batches


