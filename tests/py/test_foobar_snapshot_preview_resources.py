"""Independently selectable real-boundary tests for the pure preview.

Synthetic DTO graphs exercise finite defensive validation without large source
byte copies. They do not certify provenance. No lowered production constants,
performance promises, application startup, databases or private fixture data.
"""
import dataclasses

import pytest

from music_app.services import foobar_snapshot_parser as parser
from music_app.services import foobar_snapshot_preview as preview


FIELD_NAMES = (
    "path", "artist", "album_artist", "album", "date", "discnumber",
    "tracknumber", "title", "rating", "rating_stars", "rating_stars_fixed",
    "play_count", "play_count_enhanced", "first_played", "last_played", "added",
    "first_played_enhanced", "last_played_enhanced", "added_enhanced", "favorite",
    "length", "length_ex", "played_times", "played_times_js", "played_times_raw",
    "lastfm_played_times_js", "lastfm_play_count",
)


def clean_source(headers=("path",), cells=("x",), count=1):
    # Only path and opaque unknown headers are generated by this helper.
    observations = tuple(parser.FieldObservation("valid" if cells[headers.index(name)] else "empty",
                                                 headers.index(name), cells[headers.index(name)] or None, None)
                         if name in headers else parser.FieldObservation("absent", None, None, None)
                         for name in FIELD_NAMES)
    rows = tuple(parser.ParsedRow(i + 1, i + 2, cells, observations, 0) for i in range(count))
    return parser.ParseResult("foobar_text_tools_snapshot_v1", "parsed", "0" * 64,
                              headers, rows, parser.ParseSummary(count, count, 0, 0, 0, 0, False), ())


def build(source, inventory=(), revision="r1"):
    return preview.build_foobar_preview(source, inventory=inventory, inventory_revision=revision)


def reject(source, reason, *, inventory=(), revision="r1"):
    result = build(source, inventory, revision)
    assert result.status == "rejected" and result.reason == reason
    assert result.contract_version == "foobar_snapshot_preview_v1"
    assert result.matcher_version == "foobar_exact_path_v1"
    assert result.parser_version is result.source_sha256 is result.inventory_revision is None
    assert result.rows == () and type(result.rows) is tuple
    assert tuple(getattr(result.summary, field.name) for field in dataclasses.fields(result.summary)) == (0,) * 9


def budget_inventory(multibyte=False, overflow=False):
    # 4096 * (8-byte unique file ref + 1-byte canonical ref + 16375-byte path)
    # = 67108864. Repeated strings must be charged for every entry.
    path = "é" * 8187 + "x" if multibyte else "x" * 16375
    entries = tuple(preview.InventoryEntry(f"f{i:07d}", "t", path, False) for i in range(4096))
    if overflow:
        entries = entries[:-1] + (dataclasses.replace(entries[-1], path=path + "x"),)
    assert sum(len(e.file_ref.encode()) + len(e.canonical_track_ref.encode()) + len(e.path.encode()) for e in entries) == 67108864 + int(overflow)
    return entries


@pytest.mark.parametrize("count", [100000, 100001], ids=["at-limit", "over-limit"])
def test_inventory_entry_limit_is_not_truncation(count):
    inventory = tuple(preview.InventoryEntry(f"f{i}", "t", "x", False) for i in range(count))
    source = clean_source()
    if count > 100000:
        reject(source, "inventory_too_large", inventory=inventory)
    else:
        result = build(source, inventory)
        assert result.status == "ready"
        assert result.rows[0].match_status == "exact_unique"
        assert result.rows[0].candidate_refs == ("t",) and result.rows[0].candidate_count == 1


def test_revision_validation_precedes_count_and_count_precedes_entry_validation():
    inventory = (None,) * 100001
    reject(clean_source(), "invalid_inventory_revision", inventory=inventory, revision="")
    reject(clean_source(), "inventory_too_large", inventory=inventory)


@pytest.mark.parametrize("multibyte", [False, True], ids=["ascii", "utf8"])
@pytest.mark.parametrize("overflow", [False, True], ids=["at-limit", "over-limit"])
def test_inventory_aggregate_budget_counts_repeated_strings_per_entry(multibyte, overflow):
    inventory = budget_inventory(multibyte, overflow)
    source = clean_source(cells=(inventory[0].path,))
    if overflow:
        reject(source, "inventory_too_large", inventory=inventory)
    else:
        result = build(source, inventory)
        assert result.status == "ready"
        assert result.rows[0].candidate_count == 1 and result.rows[0].suggested_track_ref == "t"


@pytest.mark.parametrize("case", ["late-invalid", "duplicate", "duplicate-and-late-invalid"],
                         ids=["invalid-over-budget", "duplicate-over-budget", "invalid-over-duplicate"])
def test_all_entries_and_duplicates_are_checked_before_aggregate_rejection(case):
    inventory = budget_inventory(overflow=True)
    if case in ("duplicate", "duplicate-and-late-invalid"):
        inventory = inventory[:1] + (dataclasses.replace(inventory[1], file_ref=inventory[0].file_ref),) + inventory[2:]
    if case in ("late-invalid", "duplicate-and-late-invalid"):
        inventory += (preview.InventoryEntry("last", "t", "x", 1),)
    reject(clean_source(), "invalid_inventory", inventory=inventory)


def test_maximum_parser_rows_are_preserved_and_share_one_candidate_projection():
    source = clean_source(count=100000)
    inventory = tuple(preview.InventoryEntry(f"f{i}", f"t{i:03}", "x", False) for i in reversed(range(101)))
    result = build(source, inventory)
    assert result.status == "ready" and len(result.rows) == 100000
    assert result.summary.rows_total == result.summary.ambiguous_rows == 100000
    candidates = tuple(f"t{i:03}" for i in range(20))
    first_projection = result.rows[0].candidate_refs
    assert first_projection == candidates
    for ordinal, row in enumerate(result.rows, 1):
        assert row.ordinal == ordinal and row.line_number == ordinal + 1
        assert row.source_row is source.rows[ordinal - 1]
        assert row.candidate_refs is first_projection
        assert row.candidate_count == 101 and row.candidates_truncated is True
        assert row.suggested_track_ref is row.duplicate_target_group is None


def test_many_distinct_path_groups_keep_exact_counts_and_bounded_candidates():
    groups, per_group = 2000, 21
    seed = clean_source()
    rows = []
    for i in range(groups):
        path = f"path-{i}"
        fields = (parser.FieldObservation("valid", 0, path, None),) + seed.rows[0].fields[1:]
        rows.append(parser.ParsedRow(i + 1, i + 2, (path,), fields, 0))
    source = dataclasses.replace(seed, rows=tuple(rows), summary=parser.ParseSummary(groups, groups, 0, 0, 0, 0, False))
    inventory = tuple(preview.InventoryEntry(f"f-{group}-{candidate}", f"t-{group}-{candidate:02}", f"path-{group}", False)
                      for group in reversed(range(groups)) for candidate in reversed(range(per_group)))
    result = build(source, inventory)
    assert result.status == "ready" and result.summary.ambiguous_rows == groups
    for i, row in enumerate(result.rows):
        assert row.candidate_refs == tuple(f"t-{i}-{candidate:02}" for candidate in range(20))
        assert row.candidate_count == per_group and row.candidates_truncated is True
    assert result.summary.duplicate_target_groups == result.summary.duplicate_target_rows == 0


def test_all_inventory_entries_can_be_distinct_candidates_without_false_uniqueness():
    inventory = tuple(preview.InventoryEntry(f"f{i}", f"t{i:06}", "x", False) for i in range(100000))
    result = build(clean_source(), inventory)
    row = result.rows[0]
    assert result.status == "ready" and row.match_status == "ambiguous"
    assert row.candidate_count == 100000 and row.candidates_truncated is True
    assert row.candidate_refs == tuple(f"t{i:06}" for i in range(20))
    assert row.suggested_track_ref is row.duplicate_target_group is None


