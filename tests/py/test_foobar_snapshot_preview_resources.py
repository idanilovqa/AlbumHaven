@pytest.mark.parametrize("where", ["header", "cell"])
@pytest.mark.parametrize("multibyte", [False, True], ids=["ascii", "utf8"])
@pytest.mark.parametrize("overflow", [False, True], ids=["at-limit", "over-limit"])
def test_parser_cell_and_header_byte_bounds(where, multibyte, overflow):
    text = "é" * 8192 if multibyte else "x" * 16384
    text += "x" if overflow else ""
    source = clean_source(("path", text), ("x", "")) if where == "header" else clean_source(cells=(text,))
    if overflow:
        reject(source, "invalid_input")
    else:
        assert build(source).status == "ready"


@pytest.mark.parametrize("where", ["header", "row"])
@pytest.mark.parametrize("overflow", [False, True], ids=["at-limit", "over-limit"])
def test_parser_record_budget_includes_tab_separators(where, overflow):
    if where == "header":
        headers = ("path",) + tuple(f"c{i:02}" + "x" * 16381 for i in range(15)) + ("tail" + "x" * (16360 + int(overflow)),)
        cells = ("x",) + ("",) * 16
        assert sum(len(c.encode()) for c in headers) + len(headers) - 1 == 262144 + int(overflow)
    else:
        headers = ("path",) + tuple(f"opaque{i}" for i in range(16))
        cells = ("x" * 16384,) * 15 + ("y" * (16368 + int(overflow)), "")
        assert sum(len(c.encode()) for c in cells) + len(cells) - 1 == 262144 + int(overflow)
    source = clean_source(headers, cells)
    if overflow:
        reject(source, "invalid_input")
    else:
        assert build(source).status == "ready"


